// Helper function to get exercises based on workout title/category
export const getExercisesForWorkout = (workout) => {
  if (!workout) return workoutExercises.fullBody;

  const title = (workout.title || '').toLowerCase();
  const category = (workout.category || '').toLowerCase();

  // Core Crusher
  if (title.includes('core') || title.includes('crusher') || title.includes('abs')) {
    return workoutExercises.coreCrusher;
  }

  // HIIT
  if (title.includes('hiit') || title.includes('blast')) {
    return workoutExercises.hiit;
  }

  // Upper Body / Strength
  if (title.includes('upper') || title.includes('strength') || title.includes('power') || category === 'strength') {
    return workoutExercises.upperBody;
  }

  // Yoga
  if (title.includes('yoga') || title.includes('flow') || category === 'yoga') {
    return workoutExercises.yoga;
  }

  // Dance
  if (title.includes('dance') || title.includes('party') || category === 'dance') {
    return workoutExercises.dance;
  }

  // Default to full body
  return workoutExercises.fullBody;
};

